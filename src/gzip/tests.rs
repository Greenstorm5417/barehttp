#[test]
fn crc32_rfc1952_appendix_vectors() {
  // Empty → 0; "123456789" is the classic check value 0xCBF43926.
  assert_eq!(crc32(b""), 0);
  assert_eq!(crc32(b"123456789"), 0xcbf4_3926);
}

#[test]
fn zlib_rejects_fdict() {
  // CMF=0x78, FLG with FDICT set and header checksum adjusted to % 31 == 0 is hard;
  // use a zlib header with FDICT bit and valid 31-check: 0x78 0x20 fails check;
  // 0x78 0x3f has FDICT and (0x783f % 31) == 0.
  let bad = [0x78u8, 0x3f, 0x00, 0x00, 0x00, 0x00];
  assert_eq!(
    decompress_http_deflate(&bad, 64),
    Err(DecompressError::InvalidInput)
  );
}

#[test]
fn gzip_rejects_truncated_optional_fields() {
  // FNAME set but no terminating NUL before EOF
  let bad = [
    0x1f, 0x8b, 0x08, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0xff, b'a', b'b',
  ];
  assert_eq!(decompress_gzip(&bad, 64), Err(DecompressError::InvalidInput));
}
