fn long_text() -> Vec<u8> {
  let unit = b"The quick brown fox jumps over the lazy dog. ";
  let mut v = Vec::new();
  while v.len() < 1800 {
    v.extend_from_slice(unit);
  }
  v.truncate(1800);
  v
}

