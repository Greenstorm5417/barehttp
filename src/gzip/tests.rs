fn limit_exceeded() {
  assert_eq!(decompress_gzip(GZIP_HI, 1), Err(DecompressError::LimitExceeded));
  assert_eq!(inflate_raw(RAW_STORED, 2), Err(DecompressError::LimitExceeded));
}

